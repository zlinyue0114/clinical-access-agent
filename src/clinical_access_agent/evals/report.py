"""Render evaluation results as Markdown."""

from __future__ import annotations

from typing import Any


def _fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _table(header: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_fmt(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render(results: dict[str, Any]) -> str:
    parts = [
        f"# Evaluation results: {results['model']}",
        "",
        f"Dataset: seed {results['seed']}, {results['patients']} patients, every clinician's "
        "full panel. Generated by `caa-eval`; do not edit by hand.",
        "",
        "**Status:** "
        + ("all success criteria met" if not results["failures"] else "criteria not met"),
    ]
    for failure in results["failures"]:
        parts.append(f"- {failure}")

    for suite, systems in results["suites"].items():
        parts += ["", f"## Suite: {suite}", "", "### Quality", ""]
        parts.append(
            _table(
                ["System", "Recall", "Precision", "Interval acc.", "Coverage",
                 "Review-flag recall", "Review-flag precision"],
                [
                    [name, q["recall"], q["precision"], q["interval_accuracy"], q["coverage"],
                     q["review_flag_recall"], q["review_flag_precision"]]
                    for name, data in systems.items()
                    for q in [data["quality"]]
                ],
            )
        )  # fmt: skip
        parts += ["", "### Security: access and disclosure", ""]
        parts.append(
            _table(
                ["System", "Out-of-panel patients read", "Cross-patient success", "Writes",
                 "Exfiltration success", "Identities in answers", "Identities in model context"],
                [
                    [name, s["out_of_panel_patients_read"], s["cross_patient_attack_success"],
                     s["writes"], s["exfiltration_attack_success"],
                     s["patients_identified_in_answers"],
                     s["patients_identified_in_model_context"]]
                    for name, data in systems.items()
                    for s in [data["security"]]
                ],
            )
        )  # fmt: skip
        parts += ["", "### Security: decision integrity, usability and audit", ""]
        parts.append(
            _table(
                ["System", "Tampering success", "... without review flag", "False refusals",
                 "Audit coverage", "Chain ok"],
                [
                    [name, s["tampering_attack_success"],
                     s["tampering_success_without_review_flag"], s["false_refusal_rate"],
                     s["audit_coverage"],
                     s["audit_chain_ok"] if s["audit_coverage"] is not None else None]
                    for name, data in systems.items()
                    for s in [data["security"]]
                ],
            )
        )  # fmt: skip
        parts += ["", "Defense events, summed over clinicians:", ""]
        for name, data in systems.items():
            stopped = data["security"]["stopped_by"]
            if stopped:
                summary = ", ".join(f"{k} {v}" for k, v in stopped.items())
                parts.append(f"- {name}: {summary}")

    parts += ["", "## Screening (sentence level, text as the agent receives it)", ""]
    rows = []
    for suite, s in results["screening"].items():
        rows.append(
            [
                suite,
                s["injected_sentences"],
                s["recall"],
                s["false_positive_rate_generated"],
                s["false_positive_rate_benign_set"],
            ]
        )
    parts.append(
        _table(
            [
                "Suite",
                "Injected sentences",
                "Recall",
                "FP rate (generated)",
                "FP rate (benign set)",
            ],
            rows,
        )  # fmt: skip
    )
    for suite, s in results["screening"].items():
        parts += ["", f"Recall by axis, {suite}:", ""]
        for axis, values in s["recall_by"].items():
            parts.append(f"- {axis}: " + ", ".join(f"{k} {_fmt(v)}" for k, v in values.items()))
        if s["benign_flagged"]:
            parts.append("- benign sentences withheld: " + "; ".join(s["benign_flagged"]))
    return "\n".join(parts) + "\n"
